'use strict';

const fs = require('fs');
const path = require('path');
const { ROOT, STATE_DIR, remove, writeIfChanged } = require('./util');

const ANDROID_DIR = path.join(ROOT, 'android');
const MAIN_DIR = path.join(ANDROID_DIR, 'app', 'src', 'main');
const RES_DIR = path.join(MAIN_DIR, 'res');
const MANIFEST = path.join(MAIN_DIR, 'AndroidManifest.xml');
const STRINGS_XML = path.join(RES_DIR, 'values', 'strings.xml');
/**
 * `@color/splash_background` for light and dark mode. styles.xml points the
 * launch theme's windowSplashScreenBackground at it: the background of the
 * launch screen Android 12 and later draw themselves (the app icon on a plain
 * colour) instead of the splash image.
 */
const SPLASH_COLOR_XML = path.join(RES_DIR, 'values', 'splash_background.xml');
const SPLASH_COLOR_NIGHT_XML = path.join(RES_DIR, 'values-night', 'splash_background.xml');

/**
 * applicationId / versionCode / versionName for android/app/build.gradle.
 * Kept apart from the web layer's active.json so that switching the web app to
 * another client can never change the identity of an Android project whose
 * resources were generated for a different one.
 */
const IDENTITY_FILE = path.join(STATE_DIR, 'android.json');

/** OneSignal looks these two drawables up by exactly these names. */
const NOTIFICATION_ICON = 'ic_stat_onesignal_default.png';
const NOTIFICATION_LARGE_ICON = 'ic_onesignal_large_icon_default.png';

/**
 * @drawable/splash_icon, the icon of the Android 12+ launch screen (see
 * styles.xml): the client's logo in drawable[-night]-nodpi/, or an alias to
 * the platform default (the app icon) in values[-night]/.
 */
const SPLASH_ICON = 'splash_icon.png';
const SPLASH_ICON_ALIAS = 'splash_icon.xml';

/**
 * Generated files inside res/drawable*: the splash as images (from
 * @capacitor/assets) or as a drawable centring the client's logo, the
 * launch screen icon and the notification icons.
 */
const GENERATED_DRAWABLES = [
  'splash.png',
  'splash.xml',
  'splash_logo.png',
  'splash_logo_dark.png',
  SPLASH_ICON,
  NOTIFICATION_ICON,
  NOTIFICATION_LARGE_ICON,
];

function exists() {
  return fs.existsSync(ANDROID_DIR);
}

/** Escapes text for the body of an Android <string> resource. */
function androidString(text) {
  return text
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/"/g, '\\"')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/^([@?])/, '\\$1');
}

function stringsXml(config) {
  const name = androidString(config.appName);
  const accent = config.notification.accentColor; // "#RRGGBB"
  return [
    "<?xml version='1.0' encoding='utf-8'?>",
    `<!-- AUTO-GENERATED by scripts/build-client.js for client "${config.client}".`,
    `     Do not edit and do not commit: change clients/${config.client}/config.json and re-run the script. -->`,
    '<resources>',
    `    <string name="app_name">${name}</string>`,
    `    <string name="title_activity_main">${name}</string>`,
    `    <string name="package_name">${config.appId}</string>`,
    `    <string name="custom_url_scheme">${config.appId}</string>`,
    '',
    '    <!-- Notification accent colour. OneSignal reads the string (ARGB, no "#");',
    '         the colour backs the FCM default declared in AndroidManifest.xml. -->',
    `    <string name="onesignal_notification_accent_color" translatable="false">FF${accent.slice(1)}</string>`,
    `    <color name="notification_accent">${accent}</color>`,
    '</resources>',
    '',
  ].join('\n');
}

function splashColorXml(config, color, mode) {
  return [
    "<?xml version='1.0' encoding='utf-8'?>",
    `<!-- AUTO-GENERATED by scripts/build-client.js for client "${config.client}".`,
    `     Do not edit and do not commit: change clients/${config.client}/config.json and re-run the script. -->`,
    '<resources>',
    `    <!-- Launch screen background on Android 12+ in ${mode} mode (assets.${mode === 'dark' ? 'splashBackgroundColorDark' : 'splashBackgroundColor'}). -->`,
    `    <color name="splash_background">${color}</color>`,
    '</resources>',
    '',
  ].join('\n');
}

/**
 * Points the Android project at `config`: Gradle identity, strings and the
 * colours the native resources refer to.
 */
function applyIdentity(config) {
  const identity = {
    client: config.client,
    appId: config.appId,
    appName: config.appName,
    version: config.version,
    buildNumber: config.buildNumber,
  };
  const outputs = [
    [IDENTITY_FILE, `${JSON.stringify(identity, null, 2)}\n`],
    [STRINGS_XML, stringsXml(config)],
    [SPLASH_COLOR_XML, splashColorXml(config, config.assets.splashBackgroundColor, 'light')],
    [SPLASH_COLOR_NIGHT_XML, splashColorXml(config, config.assets.splashBackgroundColorDark, 'dark')],
  ];
  return outputs.filter(([file, content]) => writeIfChanged(file, content)).map(([file]) => file);
}

/**
 * Deletes every generated image (launcher icons, splash screens, notification
 * icons). Called before each generation so nothing from the previous client
 * can survive, and so a failed generation leaves an obviously broken project
 * rather than one that quietly ships another brand's artwork.
 */
function cleanAssets() {
  if (!fs.existsSync(RES_DIR)) {
    return;
  }
  for (const values of ['values', 'values-night']) {
    remove(path.join(RES_DIR, values, SPLASH_ICON_ALIAS));
  }
  for (const entry of fs.readdirSync(RES_DIR, { withFileTypes: true })) {
    if (!entry.isDirectory()) {
      continue;
    }
    const dir = path.join(RES_DIR, entry.name);
    if (entry.name.startsWith('mipmap-')) {
      remove(dir);
    } else if (entry.name === 'drawable' || entry.name.startsWith('drawable-')) {
      for (const file of GENERATED_DRAWABLES) {
        remove(path.join(dir, file));
      }
      if (fs.readdirSync(dir).length === 0) {
        fs.rmdirSync(dir);
      }
    }
  }
}

function clean() {
  cleanAssets();
  for (const file of [STRINGS_XML, SPLASH_COLOR_XML, SPLASH_COLOR_NIGHT_XML]) {
    remove(file);
  }
  const nightDir = path.dirname(SPLASH_COLOR_NIGHT_XML);
  if (fs.existsSync(nightDir) && fs.readdirSync(nightDir).length === 0) {
    fs.rmdirSync(nightDir);
  }
}

module.exports = {
  RES_DIR,
  MANIFEST,
  NOTIFICATION_ICON,
  NOTIFICATION_LARGE_ICON,
  SPLASH_ICON,
  SPLASH_ICON_ALIAS,
  exists,
  applyIdentity,
  cleanAssets,
  clean,
};
