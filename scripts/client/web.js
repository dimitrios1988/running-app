'use strict';

const fs = require('fs');
const path = require('path');
const { IONIC_COLORS } = require('./config');
const {
  ROOT,
  STATE_DIR,
  contrastRgb,
  hexToRgb,
  mix,
  remove,
  rgbToHex,
  writeIfChanged,
} = require('./util');

/** Resolved config of the client the web app is currently built for. */
const ACTIVE_FILE = path.join(STATE_DIR, 'active.json');
const CLIENT_TS = path.join(ROOT, 'src', 'environments', 'client.generated.ts');
const CLIENT_SCSS = path.join(ROOT, 'src', 'theme', 'client.generated.scss');
const SECRETS_TS = path.join(ROOT, 'src', 'app', 'secrets.ts');

const BLACK = [0, 0, 0];
const WHITE = [255, 255, 255];

function banner(config, open, close = '') {
  return [
    `${open} AUTO-GENERATED by scripts/build-client.js for client "${config.client}".${close}`,
    `${open} Do not edit and do not commit: change clients/${config.client}/config.json and re-run the script.${close}`,
  ];
}

/** The client config the Angular app can import, including the feature flags. */
function clientTs(config) {
  const flags = Object.keys(config.features);
  const value = {
    client: config.client,
    appName: config.appName,
    appId: config.appId,
    version: config.version,
    buildNumber: config.buildNumber,
    api: config.api,
    oneSignal: config.oneSignal,
    theme: { colors: config.theme.colors, darkColors: config.theme.darkColors },
    features: config.features,
  };
  return [
    ...banner(config, '//'),
    '',
    '/** Name of a feature flag. Flags are declared in clients/base.config.json. */',
    `export type FeatureFlag = ${flags.length ? flags.map((f) => JSON.stringify(f)).join(' | ') : 'never'};`,
    '',
    'export interface ClientConfig {',
    '  readonly client: string;',
    '  readonly appName: string;',
    '  readonly appId: string;',
    '  readonly version: string;',
    '  readonly buildNumber: number;',
    '  readonly api: { readonly baseUrl: string; readonly appName: string };',
    '  readonly oneSignal: { readonly appId: string };',
    '  readonly theme: {',
    '    readonly colors: Readonly<Record<string, string>>;',
    '    readonly darkColors: Readonly<Record<string, string>>;',
    '  };',
    '  readonly features: Readonly<Record<FeatureFlag, boolean>>;',
    '}',
    '',
    `export const clientConfig: ClientConfig = ${JSON.stringify(value, null, 2)};`,
    '',
  ].join('\n');
}

/**
 * Six CSS variables for one Ionic colour. Shade and tint follow Ionic's own
 * colour generator (12% towards black, 10% towards white).
 */
function ionicColor(name, hex) {
  const rgb = hexToRgb(hex);
  const contrast = contrastRgb(rgb);
  const v = `--ion-color-${name}`;
  return [
    `${v}: ${hex};`,
    `${v}-rgb: ${rgb.join(', ')};`,
    `${v}-contrast: ${rgbToHex(contrast)};`,
    `${v}-contrast-rgb: ${contrast.join(', ')};`,
    `${v}-shade: ${rgbToHex(mix(rgb, BLACK, 0.12))};`,
    `${v}-tint: ${rgbToHex(mix(rgb, WHITE, 0.1))};`,
  ];
}

/**
 * The client's theme as CSS custom properties. angular.json loads this file
 * right after src/theme/variables.scss, and the selectors match the ones used
 * there (see the specificity note at the top of that file), so every value
 * here wins over the base palette.
 */
function clientScss(config) {
  const { colors, darkColors, variables, darkVariables } = config.theme;
  const light = [];
  const dark = [];

  for (const name of IONIC_COLORS) {
    if (colors[name]) {
      light.push(ionicColor(name, colors[name]));
    }
    // A colour set only for light mode is repeated in dark mode. Without that
    // the base app's own dark palette would show through for this client.
    const darkValue = darkColors[name] || colors[name];
    if (darkValue) {
      dark.push(ionicColor(name, darkValue));
    }
  }

  if (colors.accent) {
    light.push([`--app-accent-vivid: ${colors.accent};`]);
  }
  const darkAccent = darkColors.accent || colors.accent;
  if (darkAccent) {
    dark.push([`--app-accent-vivid: ${darkAccent};`]);
  }

  const asDeclarations = (map) => Object.entries(map).map(([name, value]) => `${name}: ${value};`);
  if (Object.keys(variables).length) {
    light.push(asDeclarations(variables));
  }
  if (Object.keys(darkVariables).length) {
    dark.push(asDeclarations(darkVariables));
  }

  const block = (groups, indent) =>
    groups.map((group) => group.map((line) => indent + line).join('\n')).join('\n\n');

  return [
    ...banner(config, '/*', ' */'),
    '',
    ':root {',
    block(light, '  '),
    '}',
    '',
    '@media (prefers-color-scheme: dark) {',
    '  :root.ios,',
    '  :root.md {',
    block(dark, '    '),
    '  }',
    '}',
    '',
  ].join('\n');
}

/**
 * The API settings and credentials the app's services import as
 * AUTH_CREDENTIALS / ONESIGNAL. Gitignored: the credentials come from the
 * environment and end up in the compiled bundle, never in the repository.
 */
function secretsTs(config, secrets) {
  return [
    ...banner(config, '//'),
    '',
    'export const AUTH_CREDENTIALS = {',
    `  app_url: ${JSON.stringify(config.api.baseUrl)},`,
    `  app_name: ${JSON.stringify(config.api.appName)},`,
    `  username: ${JSON.stringify(secrets.username)},`,
    `  password: ${JSON.stringify(secrets.password)},`,
    '};',
    '',
    'export const ONESIGNAL = {',
    `  app_id: ${JSON.stringify(config.oneSignal.appId)},`,
    '};',
    '',
  ].join('\n');
}

/** Writes everything the Angular build and Capacitor's config need. */
function apply(config, secrets) {
  const outputs = [
    [ACTIVE_FILE, `${JSON.stringify(config, null, 2)}\n`],
    [CLIENT_TS, clientTs(config)],
    [CLIENT_SCSS, clientScss(config)],
    [SECRETS_TS, secretsTs(config, secrets)],
  ];
  return outputs.filter(([file, content]) => writeIfChanged(file, content)).map(([file]) => file);
}

/** Name of the client the web layer was last generated for, or null. */
function activeClient() {
  if (!fs.existsSync(ACTIVE_FILE)) {
    return null;
  }
  try {
    return JSON.parse(fs.readFileSync(ACTIVE_FILE, 'utf8')).client || null;
  } catch {
    return null;
  }
}

function clean() {
  for (const file of [CLIENT_TS, CLIENT_SCSS, SECRETS_TS]) {
    remove(file);
  }
}

module.exports = { ACTIVE_FILE, apply, activeClient, clean };
